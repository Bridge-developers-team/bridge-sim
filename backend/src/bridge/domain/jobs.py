"""Job openings, the people who hire, and what the field talks about, for the
chosen path near the user. Sources:
- live listings from the Adzuna job-search API, when the server has keys and
  the country is one Adzuna covers;
- one-tap searches on the big job boards, always, for any city (hh.kz
  added in Kazakhstan, where it is the main board);
- one-tap LinkedIn searches for recruiters and team leads near the city;
- one-tap searches for current discussion of the role (LinkedIn posts,
  Reddit), newest or top of the month.
Nothing here is generated by AI, and Bridge never scrapes LinkedIn: every
people or topic result is a search the user opens on the site itself."""

from __future__ import annotations

from typing import Literal
from urllib.parse import urlencode

from bridge.domain.models import CamelModel
from bridge.domain.text import clean

# Countries the Adzuna job-search API serves (lowercase ISO codes in its URL).
ADZUNA_COUNTRIES = frozenset(
    {"us", "gb", "ca", "au", "de", "fr", "nl", "at", "be", "ch", "es", "it", "pl", "in", "sg", "nz", "za", "br", "mx"}
)

_INDEED_HOSTS = {
    "us": "www.indeed.com",
    "gb": "uk.indeed.com",
    "ca": "ca.indeed.com",
    "au": "au.indeed.com",
    "de": "de.indeed.com",
    "fr": "fr.indeed.com",
    "nl": "nl.indeed.com",
    "in": "in.indeed.com",
    "sg": "sg.indeed.com",
    "nz": "nz.indeed.com",
    "es": "es.indeed.com",
    "it": "it.indeed.com",
}


class JobListing(CamelModel):
    title: str
    company: str
    location: str
    url: str
    salary: str = ""  # "" when the listing gives none; never estimated by us
    posted: str = ""  # ISO date


class JobLink(CamelModel):
    site: str
    url: str
    hint: str = ""  # one short line on what the link finds


class JobsResult(CamelModel):
    role: str
    city: str
    country: str
    source: Literal["adzuna", "links"]
    listings: list[JobListing]
    links: list[JobLink]
    people: list[JobLink]
    topics: list[JobLink]


def normalize_country(value: object) -> str:
    code = clean(value, 2).lower()
    return code if len(code) == 2 and code.isalpha() else "us"


def _phrase(text: str) -> str:
    """Text safe to put inside a quoted search phrase: no quotes or brackets
    that would break the site's search syntax, single spaces."""
    for ch in '"()[]{}':
        text = text.replace(ch, " ")
    return " ".join(text.split())


def city_name(city: str) -> str:
    """ "Austin, TX" -> "Austin": profiles and posts write the state or country
    in many ways ("Texas", "TX", "Austin Metro"), but the city name is stable."""
    return _phrase(clean(city, 80).split(",")[0])


_RECRUITER = '(recruiter OR "talent acquisition" OR "talent partner")'
_LEAD = "(manager OR lead OR head OR director)"
_LINKEDIN_JOBS = "https://www.linkedin.com/jobs/search/?"
_LINKEDIN_PEOPLE = "https://www.linkedin.com/search/results/people/?"
_LINKEDIN_POSTS = "https://www.linkedin.com/search/results/content/?"
# LinkedIn job filters: f_E 2,3 = entry level and associate (where career
# changers are hired); f_TPR r2592000 = posted in the last 30 days.
_ENTRY_FILTERS = {"f_E": "2,3", "f_TPR": "r2592000"}


def board_links(role: str, city: str, country: str) -> list[JobLink]:
    role, city = clean(role, 80), clean(city, 80)
    where = city or ""
    indeed = _INDEED_HOSTS.get(country, "www.indeed.com")
    linkedin = {"keywords": role, "location": where}
    links = [
        JobLink(site="LinkedIn", url=_LINKEDIN_JOBS + urlencode(linkedin), hint="All openings"),
        JobLink(
            site="LinkedIn: entry level",
            url=_LINKEDIN_JOBS + urlencode(linkedin | _ENTRY_FILTERS),
            hint="Entry and associate level, last 30 days",
        ),
        JobLink(site="Indeed", url=f"https://{indeed}/jobs?" + urlencode({"q": role, "l": where}), hint="All openings"),
    ]
    if country == "kz":
        links.append(
            JobLink(
                site="hh.kz",
                url="https://hh.kz/search/vacancy?" + urlencode({"text": role}),
                hint="The main job board in Kazakhstan",
            )
        )
    return links


def people_links(role: str, city: str) -> list[JobLink]:
    """LinkedIn searches for the people who fill this role near the city.
    Recruiters first: they answer career changers more often than busy team
    leads."""
    role, town = _phrase(clean(role, 80)), city_name(city)
    near = f' "{town}"' if town else ""
    return [
        JobLink(
            site="Recruiters on LinkedIn",
            url=_LINKEDIN_PEOPLE
            + urlencode({"keywords": f'{_RECRUITER} "{role}"{near}', "origin": "GLOBAL_SEARCH_HEADER"}),
            hint="Recruiters who hire for this role" + (f" in {town}" if town else ""),
        ),
        JobLink(
            site="Team leads on LinkedIn",
            url=_LINKEDIN_PEOPLE + urlencode({"keywords": f'"{role}" {_LEAD}{near}', "origin": "GLOBAL_SEARCH_HEADER"}),
            hint="Managers of the team you would join",
        ),
    ]


def topic_links(role: str) -> list[JobLink]:
    """What people in the role are talking about this month: worth a look
    before messaging anyone, and good material for a first post."""
    quoted = f'"{_phrase(clean(role, 80))}"'
    return [
        JobLink(
            site="LinkedIn posts",
            url=_LINKEDIN_POSTS + urlencode({"keywords": quoted, "sortBy": '["date_posted"]'}),
            hint="Newest posts about the role",
        ),
        JobLink(
            site="Reddit",
            url="https://www.reddit.com/search/?" + urlencode({"q": quoted, "sort": "top", "t": "month"}),
            hint="Top discussions this month",
        ),
    ]


def salary_text(low: object, high: object, predicted: object) -> str:
    """The listing's own salary range, or "" when it has none. Adzuna marks some
    salaries as its own estimate; those are labeled as estimates."""

    def num(v: object) -> int | None:
        try:
            n = float(str(v))
        except ValueError:
            return None
        return int(n) if n > 0 else None

    lo, hi = num(low), num(high)
    if lo is None and hi is None:
        return ""
    text = f"{lo:,}–{hi:,}" if lo and hi and lo != hi else f"{lo or hi:,}"
    return text + (" (estimate)" if str(predicted) == "1" else "")


def parse_adzuna(payload: dict, limit: int = 6) -> list[JobListing]:
    """Adzuna results -> listings. Entries without a title or link are skipped."""
    out: list[JobListing] = []
    for r in payload.get("results") or []:
        if not isinstance(r, dict):
            continue
        title, url = clean(r.get("title"), 140), clean(r.get("redirect_url"), 600)
        if not title or not url.startswith("https://"):
            continue
        out.append(
            JobListing(
                title=title,
                company=clean((r.get("company") or {}).get("display_name"), 100),
                location=clean((r.get("location") or {}).get("display_name"), 100),
                url=url,
                salary=salary_text(r.get("salary_min"), r.get("salary_max"), r.get("salary_is_predicted")),
                posted=clean(r.get("created"), 10),
            )
        )
        if len(out) == limit:
            break
    return out
