"""Job openings, the people who hire, and what the field talks about, for the
chosen path near the user. Sources:
- live listings from the Adzuna job-search API, when the server has keys and
  the country is one Adzuna covers;
- one-tap searches on the big job boards, always, for any city (hh.kz
  added in Kazakhstan, where it is the main board);
- one-tap LinkedIn searches for recruiters and team leads near the city;
- one-tap searches for current discussion of the role (LinkedIn posts,
  Reddit), newest or top of the month.
Nothing here is generated by AI, and Bridge never scrapes LinkedIn: every
people or topic result is a search the user opens on the site itself."""

from __future__ import annotations

from typing import Literal
from urllib.parse import urlencode

from bridge.domain import reference
from bridge.domain.models import CamelModel
from bridge.domain.reference import Country
from bridge.domain.text import clean


class JobListing(CamelModel):
    title: str
    company: str
    location: str
    url: str
    salary: str = ""  # "" when the listing gives none; never estimated by us
    posted: str = ""  # ISO date


class JobLink(CamelModel):
    site: str
    url: str
    hint: str = ""  # one short line on what the link finds


class JobsResult(CamelModel):
    role: str
    city: str
    country: str
    source: Literal["adzuna", "links"]
    listings: list[JobListing]
    links: list[JobLink]
    people: list[JobLink]
    topics: list[JobLink]


def normalize_country(value: object) -> str:
    code = clean(value, 2).lower()
    return code if len(code) == 2 and code.isalpha() else "us"


def _phrase(text: str) -> str:
    """Search text without quotes or brackets (they would switch the site's
    search into exact-phrase or boolean mode and empty the results), single
    spaces."""
    for ch in '"()[]{}':
        text = text.replace(ch, " ")
    return " ".join(text.split())


def city_name(city: str) -> str:
    """ "Austin, TX" -> "Austin": profiles write the state or country in many
    ways ("Texas", "TX", "Austin Metro"), but the city name is stable."""
    return _phrase(clean(city, 80).split(",")[0])


def _country(code: str) -> Country | None:
    return reference.get().country(code)


def country_name(code: str) -> str:
    c = _country(code)
    return c.name if c else ""


def linkedin_geo(code: str) -> str:
    """LinkedIn's geo id for the whole country (the geoUrn people filter and
    the jobs geoId); "" where it could not be confirmed, and searches then
    name the place in text instead."""
    c = _country(code)
    return c.linkedin_geo if c else ""


def adzuna_covers(code: str) -> bool:
    c = _country(code)
    return bool(c and c.adzuna)


def field_term(field_id: str) -> str:
    """One broad word recruiters for the field put in their headline ("Tech
    recruiter", "Healthcare recruiter"). Broad on purpose: a full job title in
    a people search usually finds nobody."""
    f = reference.get().field(field_id) if field_id else None
    return f.linkedin_term if f else ""


_LINKEDIN_JOBS = "https://www.linkedin.com/jobs/search/?"
_LINKEDIN_PEOPLE = "https://www.linkedin.com/search/results/people/?"
_LINKEDIN_POSTS = "https://www.linkedin.com/search/results/content/?"
# Job filters: f_E 2,3 = entry level and associate (where career changers are
# hired); f_TPR r2592000 = posted in the last 30 days.
_ENTRY_FILTERS = {"f_E": "2,3", "f_TPR": "r2592000"}


def job_location(city: str, country: str) -> str:
    """The place as LinkedIn's location box resolves it best: "Austin, TX,
    United States", "Almaty, Kazakhstan", or just the country."""
    city, name = clean(city, 80), country_name(country)
    if city.lower() in {"remote", "anywhere"}:
        city = ""
    if city and name and not city.lower().endswith(name.lower()):
        return f"{city}, {name}"
    return city or name


def _linkedin_jobs(role: str, city: str, country: str, extra: dict[str, str] | None = None) -> str:
    params = {"keywords": _phrase(role), "location": job_location(city, country)}
    if not job_location(city, "") and linkedin_geo(country):
        params["geoId"] = linkedin_geo(country)  # whole country: the id is exact
    elif city:
        params["distance"] = "25"  # miles around the city, LinkedIn's own default radius
    return _LINKEDIN_JOBS + urlencode(params | (extra or {}))


def board_links(role: str, city: str, country: str) -> list[JobLink]:
    role, city = clean(role, 80), clean(city, 80)
    where = "" if city.lower() in {"remote", "anywhere"} else city
    indeed = (_country(country) or Country(code="", name="", currency="")).indeed_host or "www.indeed.com"
    links = [
        JobLink(site="LinkedIn", url=_linkedin_jobs(role, city, country), hint="All openings"),
        JobLink(
            site="LinkedIn: entry level",
            url=_linkedin_jobs(role, city, country, _ENTRY_FILTERS),
            hint="Entry and associate level, last 30 days",
        ),
        JobLink(site="Indeed", url=f"https://{indeed}/jobs?" + urlencode({"q": role, "l": where}), hint="All openings"),
    ]
    if country == "kz":
        links.append(
            JobLink(
                site="hh.kz",
                url="https://hh.kz/search/vacancy?" + urlencode({"text": role}),
                hint="The main job board in Kazakhstan",
            )
        )
    return links


def _people(title: str, keywords: str, country: str) -> str:
    """A LinkedIn people search with real filters: the Title filter
    (titleFreeText), the country filter (geoUrn) and a few broad keywords."""
    params = {"origin": "FACETED_SEARCH", "titleFreeText": title}
    if keywords:
        params["keywords"] = keywords
    if linkedin_geo(country):
        params["geoUrn"] = f'["{linkedin_geo(country)}"]'
    return _LINKEDIN_PEOPLE + urlencode(params)


def people_links(role: str, city: str, country: str = "us", field: str = "") -> list[JobLink]:
    """The people who hire for this path near the user. Recruiters first: they
    answer career changers more often than busy team leads. Filters, not one
    long query: title contains "recruiter" (or "manager"), the country, and
    keywords kept to one field word plus the city, so a search finds people."""
    role, town = _phrase(clean(role, 80)), city_name(city)
    if town.lower() in {"remote", "anywhere"}:
        town = ""
    name = country_name(country)
    if not linkedin_geo(country) and not town:
        town = name  # no country filter: name the place instead
    term = field_term(field)
    the = "the " if country in {"us", "gb"} else ""
    where = f" around {town}" if town and town != name else (f" in {the}{name}" if name else "")
    return [
        JobLink(
            site="Recruiters on LinkedIn",
            url=_people("recruiter", " ".join(w for w in (term, town) if w), country),
            hint=f"Recruiters{' for ' + term + ' roles' if term else ''}{where}",
        ),
        JobLink(
            site="Team leads on LinkedIn",
            url=_people("manager", " ".join(w for w in (role, town) if w), country),
            hint=f"Managers who mention this role{where}",
        ),
    ]


def topic_links(role: str) -> list[JobLink]:
    """What people in the role are talking about this month: worth a look
    before messaging anyone, and good material for a first post."""
    words = _phrase(clean(role, 80))
    return [
        JobLink(
            site="LinkedIn posts",
            url=_LINKEDIN_POSTS + urlencode({"keywords": words, "sortBy": '["date_posted"]'}),
            hint="Newest posts about the role",
        ),
        JobLink(
            site="Reddit",
            url="https://www.reddit.com/search/?" + urlencode({"q": words, "sort": "top", "t": "month"}),
            hint="Top discussions this month",
        ),
    ]


def salary_text(low: object, high: object, predicted: object) -> str:
    """The listing's own salary range, or "" when it has none. Adzuna marks some
    salaries as its own estimate; those are labeled as estimates."""

    def num(v: object) -> int | None:
        try:
            n = float(str(v))
        except ValueError:
            return None
        return int(n) if n > 0 else None

    lo, hi = num(low), num(high)
    if lo is None and hi is None:
        return ""
    text = f"{lo:,}–{hi:,}" if lo and hi and lo != hi else f"{lo or hi:,}"
    return text + (" (estimate)" if str(predicted) == "1" else "")


def parse_adzuna(payload: dict, limit: int = 6) -> list[JobListing]:
    """Adzuna results -> listings. Entries without a title or link are skipped."""
    out: list[JobListing] = []
    for r in payload.get("results") or []:
        if not isinstance(r, dict):
            continue
        title, url = clean(r.get("title"), 140), clean(r.get("redirect_url"), 600)
        if not title or not url.startswith("https://"):
            continue
        out.append(
            JobListing(
                title=title,
                company=clean((r.get("company") or {}).get("display_name"), 100),
                location=clean((r.get("location") or {}).get("display_name"), 100),
                url=url,
                salary=salary_text(r.get("salary_min"), r.get("salary_max"), r.get("salary_is_predicted")),
                posted=clean(r.get("created"), 10),
            )
        )
        if len(out) == limit:
            break
    return out
